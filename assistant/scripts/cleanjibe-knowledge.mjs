#!/usr/bin/env node
/**
 * Builds the CleanJibe help desk's knowledge module from the one file the WingFoil repo generates
 * for it (docs/copy/assistant-knowledge.md, by web/tools/make_assistant_knowledge.py):
 *
 *   node scripts/cleanjibe-knowledge.mjs <assistant-knowledge.md> [source commit or URL]
 *
 * The deploy workflow fetches the file from JanLahmann/WingFoil main; if that fails, the committed
 * module stays as it is.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [file, source = 'JanLahmann/WingFoil main'] = process.argv.slice(2);
if (!file) { console.error('usage: node scripts/cleanjibe-knowledge.mjs <assistant-knowledge.md> [source]'); process.exit(2); }
const md = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
if (md.length < 200 || md.length > 200_000) { console.error(`unexpected size: ${md.length} chars`); process.exit(1); }
const out = new URL('../src/contexts/cleanjibe/knowledge.generated.ts', import.meta.url);
writeFileSync(out, `// Generated by scripts/cleanjibe-knowledge.mjs from ${source}. Don't edit.\nexport const CLEANJIBE_KNOWLEDGE = ${JSON.stringify(`# CleanJibe — what you know\n\n${md}\n`)};\n`);
console.error(`knowledge.generated.ts ${(md.length / 1024).toFixed(0)} KB`);
