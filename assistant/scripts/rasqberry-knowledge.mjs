#!/usr/bin/env node
/**
 * Builds the RasQberry helper's knowledge module from the RasQberry-Two website sources.
 *
 *   node scripts/rasqberry-knowledge.mjs <checkout of JanLahmann/RasQberry-Two, branch gh-pages>
 *
 * Writes src/contexts/rasqberry/knowledge.generated.ts: the summary written at build time
 * (src/contexts/rasqberry/build.summary.md, committed and reviewed) followed by the website pages
 * as published on rasqberry.org, cleaned to plain Markdown (no images or HTML, links absolute).
 * The deploy workflow runs this against the current gh-pages branch, so the live helper always
 * has today's pages; the committed copy is the snapshot the tests and local runs use.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SITE = 'https://rasqberry.org';
/** Pages the build helper knows verbatim, in this order. Demo detail pages belong to the device helper. */
export const BUILD_PAGES = [
  'index.md',
  '01-3d-model/01-bill-of-materials.md',
  '01-3d-model/02-hardware-assembly-guide.md',
  '02-software/01-installation-overview.md',
  '02-software/02-system-options.md',
  '02-software/03-ab-boot.md',
  '03-quantum-computing-demos/led-display.md',
  '03-quantum-computing-demos/00-overview.md',
  '03-quantum-computing-demos/01-demo-list.md',
  '04-jans-corner/tips-and-tricks.md',
  'workshops.md',
  '05-contributing/index.md',
];

export const pageUrl = (path) => {
  const p = path.replace(/\.md$/, '').replace(/(^|\/)index$/, '');
  return `${SITE}/${p ? `${p}/` : ''}`;
};

/** Website Markdown → plain Markdown for the prompt. */
export function clean(md) {
  return md
    .replace(/^---\n[\s\S]*?\n---\n/, '') // front matter
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '') // MDX comments
    .replace(/<[A-Z]\w*\b[^>]*\/>/g, '') // MDX components such as <ModelViewer />
    .replace(/<li\b[^>]*>/gi, '- ')
    .replace(/<\/li>|<\/?(ul|ol)\b[^>]*>/gi, '')
    .replace(/<\/?b>/gi, '**')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '') // images
    .replace(/<img\b[^>]*>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/?(p|div|span|em|strong|b|i|center|sup|sub|small|details|summary|figure|figcaption|picture|source|video|iframe)\b[^>]*>/gi, '')
    .replace(/<a\s[^>]*href=['"]([^'"]+)['"][^>]*>([\s\S]*?)<\/a>/gi, '[$2]($1)')
    .replace(/\]\((\/[^)\s]*)\)/g, (_, p) => `](${SITE}${p.replace(/^\/([^#?]*?)\/?(#|\?|$)/, (_m, a, b) => `/${a}${a && !a.includes('.') ? '/' : ''}${b}`)})`)
    .replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/^[ \t]{2,}(?![-*+] |\d+\. |```)/gm, '') // indentation left over from HTML blocks (keeps nested lists)
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function main() {
  const repo = process.argv[2];
  if (!repo) { console.error('usage: node scripts/rasqberry-knowledge.mjs <RasQberry-Two gh-pages checkout>'); process.exit(2); }
  const here = new URL('../src/contexts/rasqberry/', import.meta.url);
  const commit = execFileSync('git', ['-C', repo, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const summary = readFileSync(new URL('build.summary.md', here), 'utf8').trim();
  const pages = BUILD_PAGES.map((p) => `### Page: ${pageUrl(p)}\n\n${clean(readFileSync(join(repo, 'content', p), 'utf8'))}`);
  const knowledge = `# RasQberry Two — what you know\n\n${summary}\n\n## The website pages (rasqberry.org, as published)\n\n${pages.join('\n\n')}\n`;
  const out = `// Generated by scripts/rasqberry-knowledge.mjs from JanLahmann/RasQberry-Two gh-pages ${commit.slice(0, 12)}. Don't edit.\n` +
    `export const SOURCE_COMMIT = ${JSON.stringify(commit)};\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`;
  writeFileSync(new URL('knowledge.generated.ts', here), out);
  console.error(`knowledge.generated.ts: ${(knowledge.length / 1024).toFixed(0)} KB from ${BUILD_PAGES.length} pages at ${commit.slice(0, 12)}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
